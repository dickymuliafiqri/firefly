package selfupdate

import (
	"strings"
	"testing"
)

const sampleDigest = "aec070645fe53ee3b3763059376134f058cc337247c978add178b6ccdfb0019f"

func TestParseChecksums(t *testing.T) {
	input := `# generated by the release workflow
` + sampleDigest + `  firefly_v1.44.13_linux_amd64.tar.gz
b7bc2d3dd0a1cbcf0d1c0b1b8d4b3eb7b1d3a30b63b8f8e6b0b0b7e8d1b6a1c4 *firefly_v1.44.13_windows_amd64.zip
` + strings.ToUpper(sampleDigest) + `  ./dist/firefly_v1.44.13_darwin_arm64.tar.gz

not-a-checksum  firefly_ignored.tar.gz
` + sampleDigest + `
`

	sums, err := ParseChecksums(strings.NewReader(input))
	if err != nil {
		t.Fatalf("ParseChecksums failed: %v", err)
	}

	for _, name := range []string{
		"firefly_v1.44.13_linux_amd64.tar.gz",
		"firefly_v1.44.13_windows_amd64.zip",
		"firefly_v1.44.13_darwin_arm64.tar.gz",
	} {
		if _, ok := sums[name]; !ok {
			t.Fatalf("missing digest for %q in %v", name, sums)
		}
	}
	if len(sums) != 3 {
		t.Fatalf("parsed %d digests, want 3: %v", len(sums), sums)
	}
	// The binary-mode marker and a directory prefix must both be stripped.
	if got := sums["firefly_v1.44.13_linux_amd64.tar.gz"]; got != sampleDigest {
		t.Fatalf("digest = %q, want %q", got, sampleDigest)
	}
}

func TestParseChecksumsRejectsEmpty(t *testing.T) {
	if _, err := ParseChecksums(strings.NewReader("# nothing here\n")); err == nil {
		t.Fatal("expected an error for a checksum file with no digests")
	}
}
